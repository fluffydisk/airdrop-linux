'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { spawn } = require('node:child_process');
const { _electron: electron } = require('playwright-core');
const dbus = require('../desktop/node_modules/dbus-next');
test('Electron wizard uses authorized D-Bus jobs, preserves files access, opens browser login and detects a second device', async t => {
  if (!process.env.DBUS_SESSION_BUS_ADDRESS) { t.skip('Run inside dbus-run-session'); return; }
  const server = spawn('/usr/bin/python3', ['tests/system-bridge.py', '--serve'], { stdio: ['ignore', 'pipe', 'inherit'] });
  await new Promise((resolve, reject) => { server.stdout.once('data', data => String(data).includes('ready') ? resolve() : reject(new Error('Test bridge did not start'))); server.once('error', reject); });
  let app, bus;
  t.after(async () => { bus?.disconnect(); if (app) await app.close(); server.kill(); });
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'airdrop-wizard-'));
  app = await electron.launch({ executablePath: require('../desktop/node_modules/electron'), args: [path.resolve('desktop'), '--ozone-platform=x11'], env: { ...process.env, DBUS_SYSTEM_BUS_ADDRESS: process.env.DBUS_SESSION_BUS_ADDRESS, AIRDROP_HOME: root, AIRDROP_DISABLE_TRAY: '1', AIRDROP_DISABLE_UPDATE_CHECK: '1', AIRDROP_DISABLE_SETUP: '' }, timeout: 20000 });
  bus = dbus.sessionBus(); bus.on('error', () => {});
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const client = (await bus.getProxyObject('io.github.fluffydisk.Airdrop.System', '/io/github/fluffydisk/Airdrop/System')).getInterface('io.github.fluffydisk.Airdrop.System1');
  const page = await app.firstWindow();
  await app.evaluate(({ shell }) => { globalThis.loginUrls = []; shell.openExternal = async url => { globalThis.loginUrls.push(url); }; });
  await page.locator('[data-view=connection]').click();
  await page.waitForFunction(() => document.getElementById('setupAction').textContent === 'Install Tailscale');
  await client.SetAllowed(false); await page.locator('#setupAction').click();
  await page.waitForFunction(() => document.getElementById('setupMessage').textContent.includes('denied') || document.getElementById('setupMessage').textContent.includes('Denied'));
  await client.SetAllowed(true); await page.locator('#refreshConnection').click();
  await page.locator('#setupAction').click();
  await page.waitForFunction(() => document.getElementById('setupAction').textContent === 'Start Tailscale' && !document.getElementById('setupAction').disabled);
  await page.locator('#setupAction').click();
  await page.waitForFunction(() => document.getElementById('setupAction').textContent === 'Connect to Tailscale' && !document.getElementById('setupAction').disabled);
  await page.locator('#setupAction').click();
  await page.waitForFunction(() => document.getElementById('setupAction').textContent === 'Prepare private sharing' && !document.getElementById('setupAction').disabled);
  assert.deepEqual(await app.evaluate(() => globalThis.loginUrls), ['https://login.tailscale.com/a/test']);
  await page.locator('#setupAction').click();
  await page.waitForFunction(() => document.getElementById('connectionCard').dataset.state === 'no-peers');
  assert.equal(await page.locator('#setupQr').isVisible(), true);
  await fs.mkdir('.test-artifacts', { recursive: true }); await page.screenshot({ path: '.test-artifacts/setup-no-peers.png' });
  await client.SetOnlinePeers(true); await page.locator('#refreshConnection').click();
  await page.waitForFunction(() => document.getElementById('connectionCard').dataset.state === 'connected');
  await page.locator('[data-view=files]').click(); assert.equal(await page.locator('#fileExplorer').isVisible(), true);
});
