'use strict';
// Actual source desktop/helper lifecycle. Synthetic observations below are NOT phone evidence.
const test = require('node:test'), assert = require('node:assert/strict');
const fs = require('node:fs/promises'), path = require('node:path'), os = require('node:os');
const { spawn, execFile } = require('node:child_process');
const { promisify } = require('node:util');
const execute = promisify(execFile);
const script = path.resolve('scripts/quickshare-android-lab.cjs');
const { listener } = require('../scripts/quickshare-android-lab.cjs');
test('S24 lab prepares, launches actual Electron/helper, collects privately and stops only its own app', { timeout: 180000 }, async t => {
  assert.ok(process.env.DISPLAY || process.env.WAYLAND_DISPLAY, 'Run with Xvfb or a graphical session; keep sandboxing enabled');
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 's24-lab-native-'));
  const unrelated = spawn(process.execPath, ['-e', 'setInterval(()=>{},1000)'], { stdio: 'ignore' });
  const cliAt = (workspace,...args) => execute(process.execPath, [script, ...args, '--workspace', workspace], { cwd: process.cwd(), env: process.env, timeout: 90000, maxBuffer: 1024 * 1024 });
  const cli=(...args)=>cliAt(root,...args);
  t.after(async () => { await cli('--stop').catch(() => {}); unrelated.kill('SIGTERM'); await fs.rm(root, { recursive: true, force: true }); });
  const native = process.env.AIRDROP_TEST_QUICKSHARE_BLE_NATIVE === '1';
  await cli('--prepare', '--skip-install', ...(native ? ['--ble-native'] : []));
  const start = await cli('--start'); assert.match(start.stdout, /DEVELOPMENT BUILD/); assert.match(start.stdout, /Airdrop S24 Lab/);
  const status = JSON.parse((await cli('--status')).stdout);
  assert.equal(status.status, 'running'); assert.equal(status.helperStatus, 'ready'); assert.equal(status.listenerReachable, true);
  const marker = JSON.parse(await fs.readFile(path.join(root, 'lab.json')));
  const port = JSON.parse(await fs.readFile(path.join(root, 'desktop-state.json'))).helper.listenerPort;
  await cli('--collect', '--non-interactive', '--direction', 'samsung-to-linux', '--case', 'lab-small.txt', '--record', 'C=fail', '--archive');
  const value = JSON.parse(await fs.readFile(path.join(root, 'reports/quickshare-test-results.json')));
  assert.equal(value.productionAcceptanceEstablished, false);
  assert.equal(value.stages.A.status, 'pass'); assert.equal(value.stages.C.evidence.startsWith('owner-reported'), true);
  assert.equal(value.stages.F.status, 'not-tested'); assert.equal(value.stages.J.status, 'not-tested');
  assert.equal(value.failure.category, native ? 'SAMSUNG_DISCOVERY_FAILED' : 'DISCOVERY_UNAVAILABLE_BLE_NOT_IMPLEMENTED');
  assert.equal(marker.bleNativeRequested, native);
  assert.equal(value.build.capabilities.gattBootstrap, native);
  if (native) { assert.equal(typeof value.session.bluetooth.stage, 'string'); assert.equal(value.session.runtimeCapabilities.lanListening, true); }
  assert.equal(JSON.stringify(value).includes(root), false); assert.equal(JSON.stringify(value).includes('127.0.0.1'), false);
  await cli('--stop'); assert.equal(unrelated.exitCode, null); process.kill(unrelated.pid, 0);
  for (let i = 0; i < 40 && await listener(port); i++) await new Promise(resolve => setTimeout(resolve, 100));
  assert.equal(await listener(port), false, 'owned native receiver must stop listening');
  await assert.rejects(fs.lstat(path.join(root, 'control.sock')), { code: 'ENOENT' });
  await assert.rejects(fs.lstat(path.join(root, 'run.lock')), { code: 'ENOENT' });
  await cli('--collect', '--non-interactive');
  assert.equal(JSON.parse(await fs.readFile(path.join(root, 'reports/quickshare-test-results.json'))).stages.A.status, 'pass');
  await cli('--start');
  const nextMarker = JSON.parse(await fs.readFile(path.join(root, 'lab.json'))); assert.notEqual(nextMarker.run, marker.run);
  await cli('--collect', '--non-interactive', '--direction', 'samsung-to-linux', '--case', 'lab-small.txt');
  const fresh = JSON.parse(await fs.readFile(path.join(root, 'reports/quickshare-test-results.json')));
  assert.equal(fresh.stages.C.status, 'not-tested', 'previous trial observations cannot carry over');
  await cli('--stop'); process.kill(unrelated.pid, 0);
  if(native){
    const deepRoot=path.join(root,'fresh-deep');
    await cliAt(deepRoot,'--diagnose','--direction','linux-to-samsung','--duration','10','--network','ordinary','--archive','--skip-install');
    const deep=JSON.parse(await fs.readFile(path.join(deepRoot,'reports/quickshare-deep-diagnostic.json')));
    assert.equal(deep.build.helperHashVerified,true,`capture=${deep.captureOutcome}; failedStage=${deep.failedStage}; helper hash verification`);assert.equal(deep.build.sourceVerified,true);
    assert.equal(deep.captureOutcome,'completed');assert.equal(deep.shutdown.classification,'clean-stop');
    assert.equal(deep.lan.listenerReachable,true);assert.equal(deep.lan.listenerReachableAfterShutdown,false);assert.equal(deep.transfer.selectedTransport,'unknown');
    const timeline=JSON.parse(await fs.readFile(path.join(deepRoot,'reports/quickshare-event-timeline.json')));assert.equal(timeline.events.some(e=>e.type==='connection'),false,'listener probes must not create Nearby attempts');
    assert.equal(deep.transfer.outcome,'unconfirmed');assert.equal(deep.samsungCompatibilityEstablished,false);
    assert.equal(JSON.stringify(deep).includes(root),false);
    await assert.rejects(fs.lstat(path.join(deepRoot,'control.sock')),{code:'ENOENT'});
    assert.equal((await fs.readdir(deepRoot)).includes('diagnose.lock'),false);
  }
});
