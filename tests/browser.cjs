'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const express = require('express');
const { chromium } = require('playwright-core');
const JSZip = require('jszip');
const { createServer } = require('../push-server');
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
async function until(fn) { for (let i = 0; i < 150; i++) { if (await fn()) return; await sleep(50); } throw new Error('Timed out waiting for files'); }
test('Chromium: immediate uploads, ZIP, Android shares, folders, selection, trash, native downloads and real clipboard paste', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'airdrop-browser-'));
  const share = path.join(root, 'files'); await fs.mkdir(share);
  const service = createServer({ watchDir: share, stateDir: path.join(root, 'state'), watch: false });
  const app = express(); app.use('/push', service.app); app.use('/ui', express.static(path.resolve('ui')));
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  t.after(async () => { await browser.close(); service.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await fs.rm(root, { recursive: true, force: true }); });
  const context = await browser.newContext({ acceptDownloads: true, permissions: ['clipboard-read', 'clipboard-write'] }); const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '/ui/'); await page.evaluate(() => navigator.serviceWorker.ready); await page.reload();
  await page.locator('#fileInput').setInputFiles([{ name: 'ü,a.txt', mimeType: 'text/plain', buffer: Buffer.from('first') }]);
  await page.waitForFunction(() => document.getElementById('status').textContent === '1 uploaded');
  assert.equal(await fs.readFile(path.join(share, 'ü,a.txt'), 'utf8'), 'first');
  await page.locator('#sendZip').check();
  await page.locator('#fileInput').setInputFiles([{ name: 'same.txt', mimeType: 'text/plain', buffer: Buffer.from('one') }, { name: 'same.txt', mimeType: 'text/plain', buffer: Buffer.from('two') }]);
  await until(async () => (await fs.readdir(share)).some(name => name.endsWith('.zip')));
  const zipName = (await fs.readdir(share)).find(name => name.endsWith('.zip'));
  const zip = await JSZip.loadAsync(await fs.readFile(path.join(share, zipName)));
  assert.equal(await zip.file('same.txt').async('string'), 'one'); assert.equal(await zip.file('same (1).txt').async('string'), 'two');
  await page.waitForFunction(() => !document.getElementById('sendZip').disabled); await page.locator('#sendZip').uncheck();
  await page.evaluate(() => {
    const form = document.createElement('form'); form.method = 'POST'; form.enctype = 'multipart/form-data'; form.action = '/ui/share-target.html';
    const input = document.createElement('input'); input.type = 'file'; input.name = 'files'; input.multiple = true;
    const transfer = new DataTransfer(); transfer.items.add(new File(['shared'], 'android,ü.txt')); input.files = transfer.files;
    form.append(input); document.body.append(form); form.submit();
  });
  await until(async () => (await fs.readdir(share)).includes('android,ü.txt'));
  await page.waitForFunction(() => document.getElementById('status').textContent === '1 uploaded');
  assert.equal(await fs.readFile(path.join(share, 'android,ü.txt'), 'utf8'), 'shared');
  const stagedCount = await page.evaluate(async () => {
    const db = await new Promise(resolve => { const request = indexedDB.open('airdrop-shares', 1); request.onsuccess = () => resolve(request.result); });
    const count = await new Promise(resolve => { const request = db.transaction('shares').objectStore('shares').count(); request.onsuccess = () => resolve(request.result); }); db.close(); return count;
  }); assert.equal(stagedCount, 0);
  const manager = page.locator('#fileListCard');
  await manager.getByRole('button', { name: 'New folder', exact: true }).click();
  await manager.getByRole('textbox', { name: 'Folder name' }).fill('Belgeler'); await manager.getByRole('button', { name: 'Create', exact: true }).click();
  const folderRow = manager.locator('.explorer-item[data-path="Belgeler"]');
  await folderRow.locator('.explorer-name').click();
  assert.equal(await manager.getByRole('button', { name: 'Parent folder', exact: true }).isDisabled(), true);
  await folderRow.locator('.explorer-name').dblclick();
  await page.locator('#fileInput').setInputFiles([{ name: 'nested.txt', mimeType: 'text/plain', buffer: Buffer.from('nested') }]);
  await until(async () => (await fs.readdir(path.join(share, 'Belgeler'))).includes('nested.txt'));
  await page.waitForFunction(() => !document.getElementById('sendZip').disabled);
  const nestedFile = manager.locator('.explorer-item[data-path="Belgeler/nested.txt"]');
  await nestedFile.locator('.explorer-name').click();
  assert.equal(await nestedFile.locator('input').isChecked(), true);
  const openDownload = page.waitForEvent('download'); await nestedFile.locator('.explorer-name').dblclick();
  assert.equal(await fs.readFile(await (await openDownload).path(), 'utf8'), 'nested');
  await nestedFile.locator('input').uncheck();
  await page.evaluate(() => navigator.clipboard.writeText('İstanbul 👋\nİkinci satır'));
  await manager.focus(); await page.keyboard.press('Control+v');
  await until(async () => (await fs.readdir(path.join(share, 'Belgeler'))).some(name => name.startsWith('clipboard-') && name.endsWith('.txt')));
  const textName = (await fs.readdir(path.join(share, 'Belgeler'))).find(name => name.startsWith('clipboard-') && name.endsWith('.txt'));
  assert.equal(await fs.readFile(path.join(share, 'Belgeler', textName), 'utf8'), 'İstanbul 👋\nİkinci satır');
  await page.evaluate(async () => {
    const canvas = document.createElement('canvas'); canvas.width = 7; canvas.height = 5; canvas.getContext('2d').fillRect(0, 0, 7, 5);
    const png = await new Promise(resolve => canvas.toBlob(resolve, 'image/png'));
    await navigator.clipboard.write([new ClipboardItem({ 'image/png': png, 'text/plain': new Blob(['image caption'], { type: 'text/plain' }) })]);
  });
  await manager.focus(); await page.keyboard.press('Control+v');
  await until(async () => (await fs.readdir(path.join(share, 'Belgeler'))).some(name => name.endsWith('.png')));
  const pngName = (await fs.readdir(path.join(share, 'Belgeler'))).find(name => name.endsWith('.png'));
  assert.equal((await fs.readFile(path.join(share, 'Belgeler', pngName))).subarray(1, 4).toString(), 'PNG');
  await manager.getByRole('checkbox', { name: `Select ${pngName}`, exact: true }).check();
  const singleDownload = page.waitForEvent('download'); await manager.getByRole('button', { name: 'Download', exact: true }).click();
  assert.equal((await fs.readFile(await (await singleDownload).path())).subarray(1, 4).toString(), 'PNG');
  await manager.getByRole('checkbox', { name: `Select ${pngName}`, exact: true }).uncheck();
  await manager.getByRole('checkbox', { name: 'Select nested.txt', exact: true }).check();
  await manager.getByRole('checkbox', { name: `Select ${textName}`, exact: true }).check();
  await manager.getByRole('button', { name: 'Copy to folder', exact: true }).click();
  await manager.getByRole('textbox', { name: 'Folder name' }).fill('Kopyalar'); await manager.getByRole('button', { name: 'Create', exact: true }).click();
  await until(async () => (await fs.readdir(path.join(share, 'Belgeler'))).includes('Kopyalar'));
  assert.equal(await fs.readFile(path.join(share, 'Belgeler/Kopyalar/nested.txt'), 'utf8'), 'nested');
  assert.equal(await fs.readFile(path.join(share, 'Belgeler/nested.txt'), 'utf8'), 'nested');
  await manager.getByRole('checkbox', { name: 'Select nested.txt', exact: true }).uncheck(); await manager.getByRole('checkbox', { name: `Select ${textName}`, exact: true }).uncheck();
  const folder = manager.locator('.explorer-item').filter({ has: page.locator('.explorer-name', { hasText: /^Kopyalar$/ }) });
  await folder.click({ button: 'right' }); await manager.getByRole('menuitem', { name: 'Delete', exact: true }).click();
  await manager.getByRole('button', { name: 'Undo', exact: true }).click();
  await manager.getByRole('checkbox', { name: 'Select Kopyalar', exact: true }).check();
  await manager.getByRole('button', { name: 'Delete', exact: true }).click();
  await manager.getByRole('button', { name: 'Trash', exact: true }).click();
  await manager.getByRole('checkbox', { name: 'Select Kopyalar', exact: true }).check();
  await manager.getByRole('button', { name: 'Restore', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#fileListCard .explorer-empty')?.textContent === 'Trash is empty.');
  await manager.getByRole('button', { name: 'Trash', exact: true }).click();
  await manager.getByRole('checkbox', { name: 'Select Kopyalar', exact: true }).check();
  const downloadPromise = page.waitForEvent('download'); await manager.getByRole('button', { name: 'Download', exact: true }).click();
  const downloaded = await JSZip.loadAsync(await fs.readFile(await (await downloadPromise).path()));
  assert.equal(await downloaded.file('Belgeler/Kopyalar/nested.txt').async('string'), 'nested');
  await fs.mkdir('.test-artifacts', { recursive: true }); await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: '.test-artifacts/pwa-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 }); await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: '.test-artifacts/pwa-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
});
